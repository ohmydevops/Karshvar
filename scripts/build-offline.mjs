import { buildTheme } from "./build-theme.mjs";
import { buildLoading } from "./build-loading.mjs";
import { buildFonts } from "./build-fonts.mjs";
import { buildVersion } from "./build-version.mjs";
import { isSaveEarthAsset } from "./offline-packs.mjs";
buildTheme();
await buildLoading();
await buildFonts();
import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
const root = process.argv[2]
  ? pathToFileURL(path.resolve(process.argv[2]) + path.sep)
  : new URL("../public/", import.meta.url);
await buildVersion(root);
async function walk(dir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((e) =>
        e.isDirectory()
          ? walk(new URL(e.name + "/", dir), prefix + e.name + "/")
          : [prefix + e.name],
      ),
    )
  ).flat();
}
// Dotfiles are deployment metadata, not public assets (GitHub Pages returns 404).
const assets = (await walk(root))
  .filter(
    (p) =>
      p !== "sw.js" &&
      p !== "update-manifest.json" &&
      p !== "CNAME" &&
      !/(?:^|\/)blog(?:\/|$)|^social\//i.test(p) &&
      !/(?:^|\/)(?:sitemap[^/]*\.xml|robots\.txt|google[^/]*\.html|BingSiteAuth\.xml)$|\.map$/i.test(
        p,
      ) &&
      !p.split("/").some((part) => part.startsWith(".")),
  )
  .sort();
const bundled = await build({
  entryPoints: [fileURLToPath(new URL("./sw-template.js", import.meta.url))],
  bundle: true,
  write: false,
  format: "iife",
  target: "es2022",
  define: { "process.env.NODE_ENV": '"production"' },
});
const template = bundled.outputFiles[0].text;
const hash = createHash("sha256").update(template);
const integrity = {};
const gameAssets = assets.filter(isSaveEarthAsset);
let totalBytes = 0;
let gameBytes = 0;
for (const asset of assets) {
  const bytes = await readFile(new URL(asset, root));
  totalBytes += bytes.length;
  if (isSaveEarthAsset(asset)) gameBytes += bytes.length;
  hash.update(asset).update(bytes);
  integrity[asset] =
    "sha256-" + createHash("sha256").update(bytes).digest("base64");
}
const version = hash.digest("hex").slice(0, 20);
const info = JSON.parse(
  await readFile(new URL("build-info.json", root), "utf8"),
);
await writeFile(
  new URL("update-manifest.json", root),
  JSON.stringify({
    version,
    build: info.version,
    totalBytes: totalBytes - gameBytes,
    files: assets.length - gameAssets.length,
    gameBytes,
    gameFiles: gameAssets.length,
  }) + "\n",
);
await writeFile(
  new URL("sw.js", root),
  `// Generated by scripts/build-offline.mjs. Do not edit.\nconst VERSION=${JSON.stringify(version)};\nconst ASSETS=${JSON.stringify(assets)};\nconst GAME_ASSETS=${JSON.stringify(gameAssets)};\nconst INTEGRITY=${JSON.stringify(integrity)};\n${template}`,
);
