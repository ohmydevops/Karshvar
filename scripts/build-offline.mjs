import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../public/", import.meta.url);
async function walk(dir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((e) =>
        e.isDirectory()
          ? walk(new URL(e.name + "/", dir), prefix + e.name + "/")
          : [prefix + e.name],
      ),
    )
  ).flat();
}
const assets = (await walk(root)).filter((p) => p !== "sw.js").sort();
const template = await readFile(
  new URL("./sw-template.js", import.meta.url),
  "utf8",
);
const hash = createHash("sha256").update(template);
for (const asset of assets)
  hash.update(asset).update(await readFile(new URL(asset, root)));
await writeFile(
  new URL("sw.js", root),
  `// Generated by scripts/build-offline.mjs. Do not edit.\nconst VERSION=${JSON.stringify(hash.digest("hex").slice(0, 20))};\nconst ASSETS=${JSON.stringify(assets)};\n${template}`,
);
