// Rebuild after replacing game-moon.glb. Runs once at build-authoring time, not in the browser.
import fs from "node:fs/promises";
import { createHash } from "node:crypto";
import * as THREE from "../public/vendor/three.module.min.js";
import { GLTFLoader } from "../public/vendor/GLTFLoader.js";
import { MeshoptDecoder } from "../public/vendor/meshopt_decoder.mjs";
const binary = await fs.readFile(
  new URL("../public/art/game-moon.glb", import.meta.url),
);
const jsonSize = binary.readUInt32LE(12);
const document = JSON.parse(binary.subarray(20, 20 + jsonSize).toString());
const start = 28 + jsonSize;
const data = binary.subarray(start);
document.buffers[0].uri =
  "data:application/octet-stream;base64," + data.toString("base64");
delete document.images;
delete document.textures;
delete document.samplers;
document.materials = [{}];
for (const mesh of document.meshes)
  for (const primitive of mesh.primitives) primitive.material = 0;
globalThis.ProgressEvent ??= class {
  constructor(type, values) {
    Object.assign(this, values);
    this.type = type;
  }
};
const moonAsset = await new GLTFLoader()
  .setMeshoptDecoder(MeshoptDecoder)
  .parseAsync(JSON.stringify(document), "");
const lunarRadius = 450;
const lunarMap = null;
const globe = moonAsset.scene;
globe.updateMatrixWorld(true);
const bounds = new THREE.Box3().setFromObject(globe);
const center = bounds.getCenter(new THREE.Vector3());
const size = bounds.getSize(new THREE.Vector3());
const scale = (lunarRadius * 2) / Math.max(size.x, size.y, size.z);
const meshes = [];
globe.traverse((mesh) => {
  if (mesh.isMesh) meshes.push(mesh);
});
// Bake source transforms once, preserving its authored relief, UVs and map.
for (const mesh of meshes) {
  mesh.geometry = mesh.geometry.clone().applyMatrix4(mesh.matrixWorld);
  mesh.geometry
    .translate(-center.x, -center.y, -center.z)
    .scale(scale, scale, scale);
  mesh.geometry.rotateZ(Math.PI / 2);
  mesh.geometry.translate(0, -lunarRadius, 0);
  mesh.removeFromParent();
  globe.add(mesh);
  mesh.position.set(0, 0, 0);
  mesh.quaternion.identity();
  mesh.scale.setScalar(1);
  mesh.material.map = lunarMap;
  mesh.material.emissive.setScalar(0);
  mesh.material.roughness = 1;
  mesh.material.side = THREE.FrontSide;
}
globe.position.set(0, 0, 0);
globe.quaternion.identity();
globe.scale.setScalar(1);
globe.updateMatrixWorld(true);
// A small precomputed height field joins the landing patch to actual mesh
// relief. All raycasts happen during loading, never during flight.
const ray = new THREE.Raycaster(
  new THREE.Vector3(),
  new THREE.Vector3(0, -1, 0),
);
const hits = [];
function height(x, z) {
  ray.ray.origin.set(x, lunarRadius, z);
  hits.length = 0;
  ray.intersectObjects(meshes, false, hits);
  return (
    hits[0]?.point.y ??
    -lunarRadius + Math.sqrt(lunarRadius * lunarRadius - x * x - z * z)
  );
}
const top = height(0, 0);
for (const mesh of meshes) mesh.geometry.translate(0, -top, 0);
globe.updateMatrixWorld(true);
const cells = 24,
  extent = 24,
  field = [],
  fieldUV = [];
for (let z = 0; z <= cells; z++)
  for (let x = 0; x <= cells; x++) {
    field.push(
      height(
        (x / cells) * extent * 2 - extent,
        (z / cells) * extent * 2 - extent,
      ),
    );
    fieldUV.push(hits[0]?.uv?.clone() ?? new THREE.Vector2(0.5, 0.5));
  }

const result = {
  sourceSha256: createHash("sha256").update(binary).digest("hex"),
  radius: lunarRadius,
  top,
  cells,
  extent,
  field,
  fieldUV: fieldUV.map((v) => v.toArray()),
};
await fs.writeFile(
  new URL("../public/save-earth-lunar-field.js", import.meta.url),
  "// Generated by scripts/prepare-lunar-field.mjs from game-moon.glb.\nexport const lunarField = " +
    JSON.stringify(result) +
    ";\n",
);
console.log("Baked", field.length, "lunar surface samples");
