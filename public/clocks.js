const formatters = new Map();
export function capitalTime(id, language, now = new Date()) {
  const timeZone = capitalZones[id];
  if (!timeZone) return "";
  const key = language + ":" + timeZone;
  try {
    if (!formatters.has(key))
      formatters.set(
        key,
        new Intl.DateTimeFormat(language, {
          timeZone,
          hour: "2-digit",
          minute: "2-digit",
          hourCycle: "h23",
        }),
      );
    return formatters.get(key).format(now);
  } catch {
    return "";
  }
}
