export const naturalHistoryTranslations = Object.fromEntries(
  ["ar", "tr", "fr", "ru"].map((lang, index) => [
    lang,
    Object.fromEntries(rows.map((row) => [row[0], row[index + 1]])),
  ]),
);
export function naturalHistoryText(lang, fa, en, values = {}) {
  const template =
    lang === "fa" ? fa : naturalHistoryTranslations[lang]?.[en] || en;
  return template.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}
