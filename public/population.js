const formatters = new Map();
export function populationLabel(name, id, language) {
  const population = populations[id];
  if (!Number.isSafeInteger(population)) return name;
  if (!formatters.has(language)) {
    formatters.set(language, new Intl.NumberFormat(language));
  }
  return name + " (" + formatters.get(language).format(population) + ")";
}
